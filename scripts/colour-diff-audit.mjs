#!/usr/bin/env node
/* ============================================================
   Zero-non-colour-diff audit for the brand-colour migration (brief §7).

   For every file changed since the pre-migration commit, both versions are masked —
   colour literals -> <C>, var(--token) names -> var(<T>), ?v= cache-bust tokens -> ?v=<V>,
   comments -> <comment> — and diffed line by line. What survives the mask is a change that
   is NOT a colour value, token choice or cache-bust token: new colour-only rules, or a
   regression. Generated output (product/*.html, ingredients.html) must mask to IDENTICAL.

   Also lists which changed paths fall inside the brief's §5 allowed set.
   Usage: node scripts/colour-diff-audit.mjs   -> docs/colour-migration/NON-COLOUR-DIFF.md
   ============================================================ */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { extractColours } from './lib/colour-literals.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/colour-migration/alpha-baseline.json'), 'utf8')).commit;
const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

const changed = git('diff', '--name-only', BASE).split('\n').filter(Boolean);
const untracked = git('ls-files', '--others', '--exclude-standard').split('\n').filter(Boolean);

const ALLOWED = [
  /^css\/kotiva\.css$/, /^[^/]+\.html$/, /^product\/[^/]+\.html$/,
  /^scripts\/generate-(product-pages|ingredients-page)\.js$/, /^js\/(animations|layout)\.js$/,
  /^assets\/kotiva-logo-white\.svg$/, /^assets\/(favicon-48|apple-touch-icon)\.png$/,
  /^scripts\/generate-icons\.py$/, /^package\.json$/, /^docs\//,
  /^scripts\/(validate-palette|contrast-audit|computed-style-audit|screenshot-pages|compare-screenshots|colour-inventory|colour-diff-audit)\.mjs$/,
  /^scripts\/lib\/[^/]+\.mjs$/,
];
const allowed = (p) => ALLOWED.some((re) => re.test(p));
const isGenerated = (p) => p.startsWith('product/') || p === 'ingredients.html';
const TEXT = /\.(css|html|js|mjs|json|svg|py|md|txt)$/i;

function mask(text, ext) {
  const hits = extractColours(text, ext).filter((h) => h.kind !== 'named' || h.colour);
  let out = '';
  let last = 0;
  for (const h of hits) {
    if (h.offset < last) continue;
    out += text.slice(last, h.offset) + '<C>';
    last = h.offset + h.raw.length;
  }
  out += text.slice(last);
  return out
    .replace(/\/\*[\s\S]*?\*\//g, (m) => '<comment>' + '\n'.repeat((m.match(/\n/g) || []).length))
    .replace(/<!--[\s\S]*?-->/g, (m) => '<comment>' + '\n'.repeat((m.match(/\n/g) || []).length))
    .replace(/var\(--[\w-]+/g, 'var(<T>')
    .replace(/\?v=[A-Za-z0-9._-]+/g, '?v=<V>');
}

/* line diff via LCS; returns [{type:'-'|'+', line, text}] */
function diffLines(a, b) {
  const n = a.length;
  const m = b.length;
  // trim common prefix/suffix to keep the DP small
  let p = 0;
  while (p < n && p < m && a[p] === b[p]) p++;
  let s = 0;
  while (s < n - p && s < m - p && a[n - 1 - s] === b[m - 1 - s]) s++;
  const A = a.slice(p, n - s);
  const B = b.slice(p, m - s);
  const dp = Array.from({ length: A.length + 1 }, () => new Int32Array(B.length + 1));
  for (let i = A.length - 1; i >= 0; i--) for (let j = B.length - 1; j >= 0; j--) {
    dp[i][j] = A[i] === B[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
  }
  const out = [];
  let i = 0;
  let j = 0;
  while (i < A.length && j < B.length) {
    if (A[i] === B[j]) { i++; j++; }
    else if (dp[i + 1][j] >= dp[i][j + 1]) { out.push({ type: '-', line: p + i + 1, text: A[i] }); i++; }
    else { out.push({ type: '+', line: p + j + 1, text: B[j] }); j++; }
  }
  while (i < A.length) { out.push({ type: '-', line: p + i + 1, text: A[i] }); i++; }
  while (j < B.length) { out.push({ type: '+', line: p + j + 1, text: B[j] }); j++; }
  return out;
}

let md = `# Non-colour diff audit — brand-colour migration\n\nGenerated by \`scripts/colour-diff-audit.mjs\` against \`${BASE.slice(0, 7)}\`. `;
md += `Both versions of every changed file are masked (colour literals, \`var(--token)\` names, \`?v=\` tokens, comments); only lines that still differ are listed.\n\n`;
md += `## Changed paths\n\n| Path | Status | In §5 allowed set | Masked non-colour lines |\n|---|---|---|---|\n`;
const details = [];
let generatedNonColour = 0;
let outside = 0;
for (const p of [...changed.map((x) => [x, 'modified']), ...untracked.map((x) => [x, 'new'])]) {
  const [file, status] = p;
  const ok = allowed(file);
  if (!ok) outside++;
  let count = '—';
  if (status === 'modified' && TEXT.test(file) && fs.existsSync(path.join(ROOT, file))) {
    const ext = path.extname(file).toLowerCase();
    const before = mask(git('show', `${BASE}:${file}`), ext).split(/\r?\n/);
    const after = mask(fs.readFileSync(path.join(ROOT, file), 'utf8'), ext).split(/\r?\n/);
    const d = diffLines(before, after).filter((x) => x.text.trim() !== '<comment>' && x.text.trim() !== '');
    count = String(d.length);
    if (isGenerated(file)) generatedNonColour += d.length;
    if (d.length) details.push([file, d]);
  } else if (status === 'modified') {
    count = 'binary';
  }
  md += `| \`${file}\` | ${status} | ${ok ? 'yes' : '**NO**'} | ${count} |\n`;
}
md += `\nPaths outside the allowed set: **${outside}**. Generated-output lines that differ after masking: **${generatedNonColour}** (must be 0).\n`;
if (details.length) {
  md += `\n## Remaining (non-masked) differences\n\nThese are reviewed individually in docs/COLOUR-MIGRATION.md Part B.\n`;
  for (const [file, d] of details) {
    md += `\n### ${file}\n\n\`\`\`diff\n` + d.map((x) => `${x.type} ${String(x.line).padStart(4)} ${x.text.length > 220 ? x.text.slice(0, 220) + '…' : x.text}`).join('\n') + '\n```\n';
  }
}
fs.writeFileSync(path.join(ROOT, 'docs/colour-migration/NON-COLOUR-DIFF.md'), md);
console.log(`changed: ${changed.length} modified + ${untracked.length} new; outside allowed set: ${outside}; generated non-colour lines: ${generatedNonColour}; files with residual masked diffs: ${details.length}`);
for (const [file, d] of details) console.log(`  ${file}: ${d.length} line(s)`);
process.exit(outside || generatedNonColour ? 1 : 0);
